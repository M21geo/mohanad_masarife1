"""SQLite connection + schema."""
import sqlite3

SCHEMA_VERSION = 3

SCHEMA = """
CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS wallets (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    name            TEXT NOT NULL,
    currency        TEXT NOT NULL CHECK (currency IN ('IQD','USD')),
    initial_balance INTEGER NOT NULL DEFAULT 0,      -- minor units
    sort_order      INTEGER NOT NULL DEFAULT 0,
    archived        INTEGER NOT NULL DEFAULT 0,
    hide_balance    INTEGER NOT NULL DEFAULT 0       -- 1 = always show •••• instead of the balance
);

CREATE TABLE IF NOT EXISTS categories (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    parent_id  INTEGER REFERENCES categories(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL CHECK (kind IN ('expense','income')),
    name       TEXT NOT NULL,
    icon       TEXT NOT NULL DEFAULT 'category',
    color      TEXT NOT NULL DEFAULT '#8A9A95',
    sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_cat_parent ON categories(parent_id, sort_order);

CREATE TABLE IF NOT EXISTS people (
    id   INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS transactions (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    kind         TEXT NOT NULL CHECK (kind IN ('expense','income','transfer')),
    amount       INTEGER NOT NULL CHECK (amount > 0),  -- minor units of wallet_id's currency
    wallet_id    INTEGER NOT NULL REFERENCES wallets(id),
    to_wallet_id INTEGER REFERENCES wallets(id),       -- transfers only
    to_amount    INTEGER,                              -- minor units of to_wallet's currency
    rate         REAL,                                 -- IQD per USD when currencies differ
    category_id  INTEGER REFERENCES categories(id),
    person_id    INTEGER REFERENCES people(id) ON DELETE SET NULL,
    note         TEXT NOT NULL DEFAULT '',
    date         TEXT NOT NULL,                        -- YYYY-MM-DD
    created_at   TEXT NOT NULL DEFAULT (datetime('now')),
    recurring_id INTEGER                               -- set when generated by a recurring rule
);
CREATE INDEX IF NOT EXISTS idx_tx_date   ON transactions(date);
CREATE INDEX IF NOT EXISTS idx_tx_wallet ON transactions(wallet_id);
CREATE INDEX IF NOT EXISTS idx_tx_cat    ON transactions(category_id);

CREATE TABLE IF NOT EXISTS debts (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    direction  TEXT NOT NULL CHECK (direction IN ('on','for')),  -- on = I owe, for = owed to me
    person_id  INTEGER NOT NULL REFERENCES people(id),
    currency   TEXT NOT NULL CHECK (currency IN ('IQD','USD')),
    total      INTEGER NOT NULL CHECK (total > 0),               -- minor units
    due_date   TEXT,                                             -- YYYY-MM-DD or NULL
    note       TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    wallet_id  INTEGER,                                          -- wallet the loan money moved through
    open_tx_id INTEGER,                                          -- the transaction posted when the debt was created
    inst_count INTEGER NOT NULL DEFAULT 0,                       -- installments (0 = single payment)
    inst_first TEXT,                                             -- first installment date
    inst_period TEXT NOT NULL DEFAULT 'monthly'                  -- monthly | weekly
);

CREATE TABLE IF NOT EXISTS debt_payments (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    debt_id        INTEGER NOT NULL REFERENCES debts(id) ON DELETE CASCADE,
    amount         INTEGER NOT NULL CHECK (amount > 0),          -- minor units of the debt currency
    date           TEXT NOT NULL,
    transaction_id INTEGER REFERENCES transactions(id) ON DELETE SET NULL,
    note           TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS notes (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    text       TEXT NOT NULL,
    pinned     INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS budgets (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    category_id INTEGER REFERENCES categories(id) ON DELETE CASCADE,   -- NULL = overall monthly budget
    currency    TEXT NOT NULL CHECK (currency IN ('IQD','USD')),
    amount      INTEGER NOT NULL CHECK (amount > 0)                    -- minor units per month
);

CREATE TABLE IF NOT EXISTS recurring (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    kind        TEXT NOT NULL CHECK (kind IN ('expense','income')),
    wallet_id   INTEGER NOT NULL REFERENCES wallets(id),
    amount      INTEGER NOT NULL CHECK (amount > 0),                   -- minor units of the wallet currency
    category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
    person_id   INTEGER REFERENCES people(id) ON DELETE SET NULL,
    note        TEXT NOT NULL DEFAULT '',
    frequency   TEXT NOT NULL CHECK (frequency IN ('daily','weekly','monthly','yearly')),
    every       INTEGER NOT NULL DEFAULT 1,
    start_date  TEXT NOT NULL,
    end_date    TEXT,
    done        INTEGER NOT NULL DEFAULT 0,                            -- occurrences already created
    active      INTEGER NOT NULL DEFAULT 1
);
"""

# columns added after schema v2 (for databases created by older versions)
_V3_COLUMNS = [
    ("wallets", "hide_balance", "INTEGER NOT NULL DEFAULT 0"),
    ("transactions", "recurring_id", "INTEGER"),
    ("debts", "wallet_id", "INTEGER"),
    ("debts", "open_tx_id", "INTEGER"),
    ("debts", "inst_count", "INTEGER NOT NULL DEFAULT 0"),
    ("debts", "inst_first", "TEXT"),
    ("debts", "inst_period", "TEXT NOT NULL DEFAULT 'monthly'"),
]


def connect(path: str = ":memory:") -> sqlite3.Connection:
    # Flet runs event handlers on worker threads, so the connection must be usable from any of them.
    conn = sqlite3.connect(path, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    init_schema(conn)
    return conn


def init_schema(conn: sqlite3.Connection) -> None:
    version = conn.execute("PRAGMA user_version").fetchone()[0]
    if version > SCHEMA_VERSION:
        raise RuntimeError("database was created by a newer version of the app")
    conn.executescript(SCHEMA)
    for table, col, decl in _V3_COLUMNS:  # upgrade older databases in place
        have = {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
        if col not in have:
            conn.execute(f"ALTER TABLE {table} ADD COLUMN {col} {decl}")
    conn.execute(f"PRAGMA user_version = {SCHEMA_VERSION}")
    conn.commit()
